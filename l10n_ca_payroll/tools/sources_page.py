"""Write ``static/description/sources.html`` of a payroll module.

The page lists the ``l10n_ca.payroll.source`` records of the data file
``data/l10n_ca_payroll_source_data.xml`` of the module, with the payroll
time parameters (codes starting with ``PAYROLL_PREFIXES``) whose description
cites the URL of each source, read from the ``data/time_parameters.xml``
files of every ``l10n_ca_*`` module next to it: the same link the Odoo model
computes. The output depends only on these
files, so a test can check that the committed page is up to date.

Usage: ``python3 sources_page.py <module directory>``.
"""

import html
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

SOURCE_FILE = "data/l10n_ca_payroll_source_data.xml"
PAGE_FILE = "static/description/sources.html"
JURISDICTIONS = (("federal", "Federal"), ("quebec", "Quebec"), ("ontario", "Ontario"))
STATES = {"verified": "Verified", "to_verify": "To verify"}
PAYROLL_PREFIXES = (
    "l10n_ca.federal.",
    "l10n_ca.cpp.",
    "l10n_ca.ei.",
    "l10n_ca.pd7a.",
    "l10n_ca.t4.",
    "l10n_ca.qc.",
    "l10n_ca.qpp.",
    "l10n_ca.qpip.",
    "l10n_ca.on.",
)


def _fields(record):
    return {field.get("name"): (field.text or "").strip() for field in record}


def read_sources(module_dir):
    """Return the source records of ``module_dir`` as dictionaries, in order."""
    path = Path(module_dir) / SOURCE_FILE
    sources = []
    for record in ET.parse(path).getroot().iter("record"):
        if record.get("model") != "l10n_ca.payroll.source":
            continue
        values = _fields(record)
        values["id"] = record.get("id")
        values.setdefault("sequence", "10")
        values.setdefault("state", "verified")
        sources.append(values)
    sources.sort(
        key=lambda s: (
            [key for key, _label in JURISDICTIONS].index(s["jurisdiction"]),
            int(s["sequence"]),
        )
    )
    return sources


def read_parameters(module_dir):
    """Return (code, description) of the payroll time parameters."""
    parameters = []
    for path in sorted(Path(module_dir).resolve().parent.glob("l10n_ca_*")):
        data = path / "data" / "time_parameters.xml"
        if not data.is_file():
            continue
        for record in ET.parse(data).getroot().iter("record"):
            if record.get("model") != "base.time.parameter":
                continue
            values = _fields(record)
            if values.get("code", "").startswith(PAYROLL_PREFIXES):
                parameters.append((values["code"], values.get("description", "")))
    return parameters


def render(module_dir):
    """Return the HTML page of the sources of ``module_dir``."""
    sources = read_sources(module_dir)
    parameters = read_parameters(module_dir)
    esc = html.escape
    lines = [
        "<!DOCTYPE html>",
        '<html lang="en">',
        "<head>",
        '<meta charset="utf-8" />',
        "<title>Official sources of the Canadian payroll</title>",
        "<style>",
        "body { font-family: sans-serif; margin: 1em; }",
        "table { border-collapse: collapse; width: 100%; }",
        "th, td { border: 1px solid #ccc; padding: 4px; vertical-align: top; }",
        "th { background: #eee; text-align: left; }",
        "tr.to_verify td { background: #fff4d6; }",
        "code { font-size: 90%; }",
        "</style>",
        "</head>",
        "<body>",
        "<h1>Official sources of the Canadian payroll</h1>",
        (
            "<p>Generated by <code>l10n_ca_payroll/tools/sources_page.py</code> "
            f"from <code>{esc(SOURCE_FILE)}</code>; the same records are in "
            "Payroll &gt; Configuration &gt; Canadian Official Sources. A time "
            "parameter is listed when its description cites the URL of the "
            "source.</p>"
        ),
    ]
    for key, label in JURISDICTIONS:
        group = [s for s in sources if s["jurisdiction"] == key]
        if not group:
            continue
        lines += [
            f"<h2>{esc(label)}</h2>",
            "<table>",
            (
                "<tr><th>Source</th><th>Publisher</th><th>What the payroll takes "
                "from it</th><th>Time parameters</th><th>Verification</th></tr>"
            ),
        ]
        for source in group:
            codes = sorted(
                code
                for code, description in parameters
                if source["url"] and source["url"].lower() in description.lower()
            )
            reference = source.get("reference", "")
            note = source.get("verification_note", "")
            lines += [
                f'<tr class="{esc(source["state"])}">',
                f'<td><a href="{esc(source["url"])}">{esc(source["name"])}</a>'
                + (f"<br/>{esc(reference)}" if reference else "")
                + "</td>",
                f"<td>{esc(source.get('publisher', ''))}</td>",
                f"<td>{esc(source.get('summary', ''))}</td>",
                "<td>"
                + "<br/>".join(f"<code>{esc(code)}</code>" for code in codes)
                + "</td>",
                f"<td>{esc(STATES[source['state']])}"
                + (f"<br/>{esc(note)}" if note else "")
                + "</td>",
                "</tr>",
            ]
        lines.append("</table>")
    lines += ["</body>", "</html>", ""]
    return "\n".join(lines)


def main(argv):
    module_dir = Path(argv[1])
    page = module_dir / PAGE_FILE
    page.parent.mkdir(parents=True, exist_ok=True)
    page.write_text(render(module_dir), encoding="utf-8")


if __name__ == "__main__":
    main(sys.argv)
